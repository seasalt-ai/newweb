    def should_preserve(self, text: str) -> bool:
        """Check if text should be preserved (not translated)."""
        if not isinstance(text, str):
            return True
        
        text_lower = text.lower().strip()
        
        # Check for preserved terms
        for term in self.preserve_terms:
            if term.lower() in text_lower:
                return True
        
        # Check for technical patterns
        if re.match(r'^[A-Z]+[\d\.]*$', text.strip()):  # API, G.711, etc.
            return True
        
        if re.match(r'^\d+\s*(ms|kbps|%|MHz|GB|MB|KB|min|sec|USD|\$)$', text.strip()):
            return True
        
        if re.match(r'^[\d\-\+\(\)\s]+$', text.strip()) and len(text.strip()) > 5:
            return True
        
        if '@' in text or '.com' in text or 'http' in text or 'www.' in text:
            return True
        
        if text.strip().startswith('*') and text.strip().endswith('*'):
            return True
        
        return False
    
    def translate_text(self, text: str) -> str:
        """Translate text using the comprehensive dictionary."""
        if not isinstance(text, str) or not text.strip():
            return text
        
        if self.should_preserve(text):
            return text
        
        # Direct lookup
        if text in self.translations:
            return self.translations[text]
        
        # Case-insensitive lookup
        for english, spanish in self.translations.items():
            if english.lower() == text.lower():
                # Preserve original case pattern
                if text.isupper():
                    return spanish.upper()
                elif text.istitle():
                    return spanish.title()
                elif text.islower():
                    return spanish.lower()
                else:
                    return spanish
        
        # Partial matching for common phrases
        text_lower = text.lower()
        for english, spanish in self.translations.items():
            if english.lower() in text_lower and len(english) > 3:
                return text.replace(english, spanish).replace(english.lower(), spanish.lower()).replace(english.title(), spanish.title())
        
        # Return as-is if no translation found
        return text
    
    def process_json_recursively(self, obj):
        """Process JSON structure recursively."""
        if isinstance(obj, str):
            return self.translate_text(obj)
        elif isinstance(obj, dict):
            return {key: self.process_json_recursively(value) for key, value in obj.items()}
        elif isinstance(obj, list):
            return [self.process_json_recursively(item) for item in obj]
        else:
            return obj


