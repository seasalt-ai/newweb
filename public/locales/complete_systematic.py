    def is_preserved_term(self, text: str) -> bool:
        """Check if text contains terms that should be preserved."""
        text_lower = text.lower()
        
        # Check for preserved names
        for name in self.preserve_names:
            if name.lower() in text_lower:
                return True
        
        # Check for technical patterns
        if re.match(r'^[A-Z]+[\d\.]+$', text.strip()):  # G.711, TLS 1.3
            return True
        
        if re.match(r'^\d+\s*(ms|kbps|%|MHz|GB|MB|KB|min|sec)$', text.strip()):  # 150ms, 100 kbps
            return True
        
        if re.match(r'^[\d\-\+\(\)\s]+$', text.strip()):  # Phone numbers
            return True
        
        if '@' in text or '.com' in text or 'http' in text:  # Email/URL
            return True
        
        return False
    
    def translate_text(self, text: str) -> str:
        """Translate text systematically."""
        if not isinstance(text, str) or not text.strip():
            return text
        
        # Check if this should be preserved
        if self.is_preserved_term(text):
            return text
        
        # Direct translation lookup
        if text in self.translations:
            return self.translations[text]
        
        # Case-insensitive lookup
        for english, spanish in self.translations.items():
            if english.lower() == text.lower():
                return spanish
        
        # For untranslated strings, return as-is
        return text
    
    def process_recursively(self, obj):
        """Process all values in JSON structure."""
        if isinstance(obj, str):
            return self.translate_text(obj)
        elif isinstance(obj, dict):
            return {key: self.process_recursively(val) for key, val in obj.items()}
        elif isinstance(obj, list):
            return [self.process_recursively(item) for item in obj]
        else:
            return obj


