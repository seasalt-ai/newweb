def should_preserve_word(word):
    """Check if a word should be preserved (not translated)"""
    # Remove quotes and whitespace
    clean_word = word.strip().strip('"').strip("'")
    
    # Preserve if it's in the preserve list
    if clean_word in PRESERVE_WORDS:
        return True
    
    # Preserve if it looks like a technical term (contains dots, hyphens, or is all caps)
    if '.' in clean_word or '-' in clean_word or clean_word.isupper():
        return True
    
    # Preserve if it's a number or contains numbers and special characters
    if re.match(r'^[\d\+\-\(\)\s\$\%\/]+$', clean_word):
        return True
    
    # Preserve URLs, emails, etc.
    if any(pattern in clean_word.lower() for pattern in ['http', 'www', '@', '.com', '.ai', '.io']):
        return True
    
    return False

